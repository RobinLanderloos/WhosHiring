local ns, test, eq = ...
local Store = ns.Store

local function msg(text, sender, time, extra)
  local m = { text = text, sender = sender or "Bob-Realm", channel = "Trade", time = time or 1000, realm = "Realm" }
  for k, v in pairs(extra or {}) do m[k] = v end
  return m
end

test("a recruitment message creates a guild entry", function()
  local db = Store.init(nil)
  local status, entry = Store.record(db, msg("<Night Watch> is recruiting tanks"))
  eq(status, "new", "status")
  eq(entry.name, "Night Watch", "name")
  eq(entry.lastSeen, 1000, "lastSeen")
  eq(Store.latest(entry).text, "<Night Watch> is recruiting tanks", "latest message")
  eq(Store.posterCount(entry), 1, "posters")
  eq(Store.get(db, "Realm", "night watch"), entry, "stored under realm and key")
end)

test("a message that is not recruitment is not stored", function()
  local db = Store.init(nil)
  local status = Store.record(db, msg("WTS Linen Cloth"))
  eq(status, "ignored")
  eq(next(db.guilds), nil, "nothing stored")
end)

test("a second poster from the same guild adds to the same entry", function()
  local db = Store.init(nil)
  local _, first = Store.record(db, msg("<Night Watch> is recruiting tanks", "Bob-Realm", 1000))
  local status, second = Store.record(db, msg("Night Watch is recruiting all classes, casual raiding", "Alice-Realm", 2000))
  eq(status, "updated", "status")
  eq(second, first, "same entry")
  eq(Store.posterCount(second), 2, "posters")
  eq(Store.latest(second).sender, "Alice-Realm", "latest poster")
  eq(second.lastSeen, 2000, "lastSeen")
end)

test("the player's own guild is not recorded", function()
  local db = Store.init(nil)
  local status = Store.record(db, msg("<Night Watch> is recruiting", nil, nil, { ownGuild = "Night Watch" }))
  eq(status, "ignored")
  eq(next(db.guilds), nil, "nothing stored")
end)

test("guilds with the same name on different realms are separate", function()
  local db = Store.init(nil)
  local _, a = Store.record(db, msg("<Night Watch> recruiting", "Bob-Realm", 1, { realm = "Realm" }))
  local _, b = Store.record(db, msg("<Night Watch> recruiting", "Kim-Other", 2, { realm = "Other" }))
  eq(a ~= b, true, "different entries")
end)

test("init keeps saved guilds", function()
  local saved = Store.init(nil)
  Store.record(saved, msg("<Night Watch> recruiting"))
  local db = Store.init(saved)
  eq(Store.get(db, "Realm", "night watch").name, "Night Watch")
end)

test("a message without a guild name creates an unknown entry for its poster", function()
  local db = Store.init(nil)
  local status, entry = Store.record(db, msg("We are recruiting! chill levelling guild, /w me", "Bob-Realm", 100))
  eq(status, "new", "status")
  eq(entry.name, nil, "no name")
  eq(entry.unknownPoster, "Bob-Realm", "poster")
  eq(Store.posterCount(entry), 1, "posters")
end)

test("an unknown entry merges into the guild once its poster names it", function()
  local db = Store.init(nil)
  Store.record(db, msg("We are recruiting! chill levelling guild, /w me", "Bob-Realm", 100))
  Store.record(db, msg("<Night Watch> recruiting all classes", "Alice-Realm", 150))
  local status, entry = Store.record(db, msg("<Night Watch> is recruiting, /w me", "Bob-Realm", 200))
  eq(status, "updated", "status")
  eq(entry.name, "Night Watch", "merged into the guild")
  eq(#entry.messages, 3, "messages carried over")
  eq(Store.posterCount(entry), 2, "posters")
  eq(Store.get(db, "Realm", Store.unknownKey("Bob-Realm")), nil, "unknown entry removed")
  eq(entry.firstSeen, 100, "first seen is the earliest")
end)

test("an unknown entry becomes a new guild when the named guild is not known yet", function()
  local db = Store.init(nil)
  Store.record(db, msg("We are recruiting! /w me", "Bob-Realm", 100))
  local status, entry = Store.record(db, msg("<Night Watch> is recruiting", "Bob-Realm", 200))
  eq(status, "new", "status")
  eq(#entry.messages, 2, "messages carried over")
  eq(entry.unknownPoster, nil, "no longer unknown")
end)

test("a known poster's later unnamed message goes to their guild", function()
  local db = Store.init(nil)
  Store.record(db, msg("<Night Watch> is recruiting", "Bob-Realm", 100))
  local status, entry = Store.record(db, msg("We are recruiting! /w me", "Bob-Realm", 200))
  eq(status, "updated", "status")
  eq(entry.name, "Night Watch", "same guild")
end)

test("an identical repeat from the same poster counts instead of adding a message", function()
  local db = Store.init(nil)
  Store.record(db, msg("<Night Watch> is recruiting tanks", "Bob-Realm", 100))
  local _, entry = Store.record(db, msg("<Night Watch>  is recruiting TANKS", "Bob-Realm", 400))
  eq(#entry.messages, 1, "messages")
  eq(entry.messages[1].count, 2, "count")
  eq(entry.messages[1].first, 100, "first")
  eq(entry.messages[1].last, 400, "last")
  eq(entry.messages[1].text, "<Night Watch>  is recruiting TANKS", "latest wording kept")
end)

test("the same text from another poster is a separate message", function()
  local db = Store.init(nil)
  Store.record(db, msg("<Night Watch> is recruiting tanks", "Bob-Realm", 100))
  local _, entry = Store.record(db, msg("<Night Watch> is recruiting tanks", "Alice-Realm", 200))
  eq(#entry.messages, 2, "messages")
end)

test("posters lists each poster once with their messages, newest first", function()
  local db = Store.init(nil)
  Store.record(db, msg("<Night Watch> is recruiting tanks", "Bob-Realm", 100))
  Store.record(db, msg("<Night Watch> recruiting healers too", "Alice-Realm", 200))
  local _, entry = Store.record(db, msg("<Night Watch> recruiting, raids wed/thu", "Bob-Realm", 300))
  local posters = Store.posters(entry)
  eq(#posters, 2, "posters")
  eq(posters[1].sender, "Bob-Realm", "most recent poster first")
  eq(#posters[1].messages, 2, "Bob's messages")
  eq(posters[1].messages[1].text, "<Night Watch> recruiting, raids wed/thu", "newest message first")
  eq(posters[1].lastSeen, 300, "poster last seen")
end)

test("a guild's tags are the union of its messages' tags", function()
  local db = Store.init(nil)
  Store.record(db, msg("<Night Watch> is recruiting tanks for MC", "Bob-Realm", 100))
  local _, entry = Store.record(db, msg("<Night Watch> recruiting healers, casual", "Alice-Realm", 200))
  eq(entry.tags.tank, "tanks", "tank from Bob")
  eq(entry.tags.healer, "healers", "healer from Alice")
  eq(entry.tags.raiding, "mc", "raiding")
  eq(entry.tags.casual, "casual", "casual")
end)

test("tags of an unknown entry carry over when it merges", function()
  local db = Store.init(nil)
  Store.record(db, msg("We are recruiting priests! /w me", "Bob-Realm", 100))
  local _, entry = Store.record(db, msg("<Night Watch> is recruiting", "Bob-Realm", 200))
  eq(entry.tags.priest, "priests")
end)

test("a dismissed guild is no longer recorded", function()
  local db = Store.init(nil)
  local _, entry = Store.record(db, msg("<Night Watch> is recruiting", "Bob-Realm", 100))
  Store.dismiss(db, entry, 150)
  eq(Store.get(db, "Realm", "night watch"), nil, "removed from the list")
  local status = Store.record(db, msg("<Night Watch> recruiting again", "Alice-Realm", 200))
  eq(status, "dismissed", "status")
  eq(Store.get(db, "Realm", "night watch"), nil, "still not stored")
  status = Store.record(db, msg("We are recruiting, /w me", "Bob-Realm", 300))
  eq(status, "dismissed", "an unnamed message from its known poster is dismissed too")
end)

test("dismissing an unknown entry dismisses its poster", function()
  local db = Store.init(nil)
  local _, entry = Store.record(db, msg("We are recruiting! /w me", "Bob-Realm", 100))
  Store.dismiss(db, entry, 150)
  eq(Store.record(db, msg("We are recruiting again! /w me", "Bob-Realm", 200)), "dismissed", "unnamed again")
  local status, guild = Store.record(db, msg("<Night Watch> is recruiting", "Bob-Realm", 300))
  eq(status, "new", "a named guild from that poster is not dismissed")
  eq(Store.hasDismissedPoster(db, guild), true, "but it carries the hint")
end)

test("restoring brings a dismissed guild back with its last message", function()
  local db = Store.init(nil)
  local _, entry = Store.record(db, msg("<Night Watch> is recruiting tanks", "Bob-Realm", 100))
  Store.dismiss(db, entry, 150)
  local restored = Store.restore(db, "Realm|night watch")
  eq(restored.name, "Night Watch", "name")
  eq(Store.latest(restored).text, "<Night Watch> is recruiting tanks", "last message kept")
  eq(restored.tags.tank, "tanks", "tags")
  eq(Store.get(db, "Realm", "night watch"), restored, "back in the list")
  eq(Store.record(db, msg("<Night Watch> recruiting", "Kim-Realm", 300)), "updated", "recorded again")
end)

test("restoring a dismissed poster lets their messages in again", function()
  local db = Store.init(nil)
  local _, entry = Store.record(db, msg("We are recruiting! /w me", "Bob-Realm", 100))
  Store.dismiss(db, entry, 150)
  Store.restore(db, "Realm|" .. Store.unknownKey("Bob-Realm"))
  eq(Store.record(db, msg("We are recruiting again! /w me", "Bob-Realm", 200)), "updated")
end)

test("starring marks an entry and can be undone", function()
  local db = Store.init(nil)
  local _, entry = Store.record(db, msg("<Night Watch> is recruiting", "Bob-Realm", 100))
  Store.star(entry, true)
  eq(entry.starred, true, "starred")
  Store.star(entry, false)
  eq(entry.starred, nil, "unstarred")
end)

test("settings get their defaults and keep saved values", function()
  local db = Store.init(nil)
  eq(db.settings.staleDays, 14, "stale")
  eq(db.settings.pruneDays, 60, "prune")
  eq(db.settings.maxMessages, 20, "cap")
  local saved = Store.init({ settings = { pruneDays = 90 } })
  eq(saved.settings.pruneDays, 90, "saved kept")
  eq(saved.settings.staleDays, 14, "missing filled in")
end)

test("a guild keeps only its newest messages up to the cap", function()
  local db = Store.init(nil)
  db.settings.maxMessages = 3
  local entry
  for i = 1, 5 do
    _, entry = Store.record(db, msg("<Night Watch> is recruiting, message " .. i, "Bob-Realm", i * 10))
  end
  eq(#entry.messages, 3, "capped")
  local texts = {}
  for _, m in ipairs(entry.messages) do texts[#texts + 1] = m.text:match("%d$") end
  table.sort(texts)
  eq(table.concat(texts), "345", "newest kept")
end)

test("prune removes old unstarred guilds and keeps starred and dismissed", function()
  local db = Store.init(nil)
  local day = 86400
  local _, old = Store.record(db, msg("<Old> is recruiting", "A-Realm", 0))
  local _, starred = Store.record(db, msg("<Starred> is recruiting", "B-Realm", 0))
  local _, gone = Store.record(db, msg("<Gone> is recruiting", "C-Realm", 0))
  Store.record(db, msg("<Fresh> is recruiting", "D-Realm", 50 * day))
  Store.star(starred, true)
  Store.dismiss(db, gone, 1)
  local removed = Store.prune(db, 61 * day)
  eq(removed, 1, "removed count")
  eq(Store.get(db, "Realm", "old"), nil, "old pruned")
  eq(Store.get(db, "Realm", "starred") ~= nil, true, "starred kept")
  eq(Store.get(db, "Realm", "fresh") ~= nil, true, "fresh kept")
  eq(db.dismissed["Realm|gone"] ~= nil, true, "dismissed kept")
  eq(db.posters["A-Realm"], nil, "poster link of a pruned guild forgotten")
  eq(db.posters["C-Realm"], "gone", "poster link of a dismissed guild kept")
end)

test("day settings accept whole numbers in range only", function()
  eq(Store.parseDays("30", 1, 365), 30, "plain")
  eq(Store.parseDays(" 7 ", 1, 365), 7, "spaces")
  eq(Store.parseDays("0", 1, 365), nil, "below range")
  eq(Store.parseDays("1000", 1, 365), nil, "above range")
  eq(Store.parseDays("abc", 1, 365), nil, "not a number")
  eq(Store.parseDays("2.5", 1, 365), nil, "not whole")
end)
